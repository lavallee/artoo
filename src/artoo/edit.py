"""Open an artifact in an in-page editor: ``artoo edit``.

Artoo does not edit pages itself. It hands the built site, its source map and
the artifact's edit settings to Copycat, an editor that serves the page with
editing on it and writes changes back to the Markdown sources. Copycat is a
soft dependency like flip: it is found through ``--copycat`` or
``COPYCAT_HOME``, and nothing here runs without it.

The editor's configuration is the artifact's own ``[edit] config`` when the
manifest names one (registered files are the editor's write boundary, so an
artifact with generated figure text or a masthead in TOML keeps an explicit
file). Otherwise one is generated into ``work/editor/copycat.json`` from the
source map: every Markdown file the pages were rendered from, the manifest
title, comments and section status where ``[edit]`` puts them, and
``artoo build --no-browser .`` as the rebuild that runs after each save.

A deck is the exception to the source map. Its source is ``site/index.html``
itself, hand-authored, with no ``[content]`` table and nothing to build, so
there is nothing to map: the generated configuration registers that one file
as an HTML source and tells the editor the page is a deck.
"""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path
from urllib.parse import urlsplit

from . import sourcemap
from .libraries import deck as deck_library
from .manifest import Manifest

GENERATED = Path("work") / "editor" / "copycat.json"

# Kit blocks that wrap ordinary Markdown, as the element and class each one renders to.
LIVE_CONTAINERS = {
    "wide": "div.article-breakout",
    "full": "div.article-full",
}


DECK_PAGE = "index.html"
DECK_STAGE = "main.deck-stage"
# Attributes of a deck the editor may change: a slide's act and short label, and the
# text alternatives of images.
DECK_ATTRIBUTES = ["data-short", "data-act", "alt", "title"]


class EditError(Exception):
    """A road sign: what is missing and the flag, key or command that fixes it."""


def copycat_home(explicit: Path | None = None) -> Path:
    candidate = explicit or (Path(os.environ["COPYCAT_HOME"]) if os.environ.get("COPYCAT_HOME") else None)
    if candidate is None:
        raise EditError(
            "artoo edit needs Copycat: pass --copycat DIR or set COPYCAT_HOME to its checkout"
        )
    if not (candidate / "src" / "server.js").is_file():
        raise EditError(f"{candidate} is not a Copycat checkout (no src/server.js); fix --copycat or COPYCAT_HOME")
    return candidate.resolve()


def check_origin(origin: str) -> str:
    share = urlsplit(origin)
    if share.scheme != "https" or not share.netloc or origin != f"https://{share.netloc}" or share.username:
        raise EditError(f"--share-origin must be an exact https:// origin such as https://host.example, not {origin!r}")
    return origin


def is_deck(m: Manifest) -> bool:
    """A deck authored as HTML: form deck (or kind presentation), and no [content] to render."""
    return m.effective_form == "deck" and not (m.content_source or m.content_pages)


def deck_format() -> str:
    """What the editor's agent is told about a deck's markup, from the library's own vocabulary."""
    generated = "generated by deck.js"
    chrome = {"deck-root", "deck-bar", "deck-mark", "deck-who", "deck-spacer", "deck-pager", "deck-pager-m",
              "deck-counter", "deck-progress", "deck-stage", "deck-slide", "deck-inner", "deck-help", "deck-help-card"}
    content = [
        name for name, meaning in deck_library.CLASSES.items()
        if name not in chrome and "(generated)" not in meaning and generated not in meaning and name != "deck-overview"
    ]
    return (
        "The document is one HTML file: a slide deck built on artoo-deck, and the file is the page itself "
        "(there is no build step). Slides are the <section class=\"deck-slide\" data-act=\"…\" data-short=\"…\"> "
        "elements inside <main class=\"deck-stage\" data-deck>, in order. data-act groups consecutive slides into "
        "an act in the overview; data-short is the slide's short label there. A slide's content is in "
        "<div class=\"deck-inner\">; its speaker note is <aside class=\"deck-notes\"><b>Speaker note</b><p>…</p></aside> "
        "at the end of that box. Edit by exact find and replace on the HTML: copy \"find\" from the file, tags and "
        "indentation included, and write valid HTML in \"replace\" with &amp; &lt; &gt; escaped in text. "
        "The deck- class prefix is load-bearing and belongs to the library: use only these content classes, as the "
        f"file already uses them: {', '.join(content)}. Never invent a class that starts with deck-, and give any "
        "class of your own a name outside that prefix (the artifact's own <style> is where it is defined). "
        "Do not touch the <head>, header.deck-bar, the overview, help or script elements. "
        "A slide that needs scrolling is two slides: prefer fewer words."
    )


def deck_config(m: Manifest, port: int) -> dict:
    """A Copycat configuration for a hand-authored deck: one HTML source, edited on the slide."""
    page_file = Path(m.site) / DECK_PAGE
    if not (m.dir / page_file).is_file():
        raise EditError(f"this deck has no {page_file.as_posix()} to edit; `artoo init --form deck` writes one")
    path = f"/{m.slug}/"
    source: dict = {
        "file": page_file.as_posix(),
        "html": True,
        # The draft is the file's text, held by the editor and shared by every browser on
        # the page; slides, notes and structure are edited in it by offset.
        "live": True,
        "scope": DECK_STAGE,
        "label": "Slides",
        "attributes": DECK_ATTRIBUTES,
        # Labels drawn as SVG <text> inside a deck-figure can be reworded in place.
        "svgText": ".deck-figure",
        "status": bool(m.edit_status),
    }
    page: dict = {
        "name": m.title,
        "url": f"http://127.0.0.1:{port}{path}{DECK_PAGE}",
        "selector": DECK_STAGE,
        "deck": True,
        "serve": {"dir": m.site, "path": path},
        "conflicts": "file",
        "sources": [source],
        # Nothing is rendered from a deck's source, so there is no rebuild. The same command
        # is cheap on a deck (no browser, no render) and still lints it: a deck- class the
        # library does not define is reported after the save that introduced it.
        "build": {"command": ["artoo", "build", "--no-browser", "."], "timeout": 120, "check": True},
        "chat": {"format": deck_format()},
    }
    if m.edit_comments:
        page["comments"] = m.edit_comments
    if m.edit_status:
        page["status"] = {"file": m.edit_status}
    return {"root": "../..", "state": "copycat", "pages": [page]}


def generated_config(m: Manifest, port: int) -> dict:
    """A Copycat configuration derived from the source map and [edit]."""
    if is_deck(m):
        return deck_config(m, port)
    data = sourcemap.read(m.dir)
    if data is None:
        raise EditError(
            "no source map: set `sourcemap = true` under [content] in artifact.toml, then `artoo build`"
        )
    markdown_files = sorted(
        {
            block["file"]
            for page in data["pages"].values()
            for block in page["blocks"]
            if block["file"].endswith(".md") and not block["file"].startswith("..")
        }
    )
    sources: list[dict] = [
        {
            "file": "artifact.toml",
            "toml": ["artifact.title"],
            "scope": ".site-nav .brand, .article-masthead",
            "label": "Title",
        }
    ]
    for name in markdown_files:
        source = {
            "file": name,
            "markdown": True,
            "title": True,
            "frontmatter": ["description"],
            "scope": "main.article",
            "sourceView": True,
            "status": bool(m.edit_status),
        }
        if m.edit_live:
            # Copycat draws the page from the draft itself, so it edits like a document. It
            # does so only where the page is the source drawn block for block, and edits the
            # page as before everywhere else. The kit's layout blocks are named so text
            # inside them stays editable.
            source["live"] = True
            source["containers"] = LIVE_CONTAINERS
        sources.append(source)
    path = f"/{m.slug}/"
    page: dict = {
        "name": m.title,
        "url": f"http://127.0.0.1:{port}{path}index.html",
        "selector": "main.article",
        "serve": {"dir": m.site, "path": path},
        "conflicts": "file",
        "sourcemap": str(sourcemap.MAP_FILE),
        "sources": sources,
        "build": {"command": ["artoo", "build", "--no-browser", "."], "timeout": 300},
    }
    if m.edit_comments:
        page["comments"] = m.edit_comments
    if m.edit_status:
        page["status"] = {"file": m.edit_status}
    # Paths in a Copycat config are relative to the config file.
    return {"root": "../..", "state": "copycat", "pages": [page]}


def config_path(m: Manifest, port: int) -> Path:
    if m.edit_config:
        path = m.dir / m.edit_config
        if not path.is_file():
            raise EditError(f"[edit] config names {m.edit_config}, which does not exist")
        return path
    config = generated_config(m, port)
    path = m.dir / GENERATED
    path.parent.mkdir(parents=True, exist_ok=True)
    for name in (m.edit_comments, m.edit_status):
        if name:
            (m.dir / name).parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    return path


def command(
    m: Manifest,
    *,
    copycat: Path,
    port: int,
    share_origin: str = "",
    agent: str = "none",
    agent_bin: str = "",
) -> tuple[list[str], dict[str, str]]:
    """The editor's command line and environment; ``launch`` runs it."""
    node = shutil.which("node")
    if not node:
        raise EditError("artoo edit needs Node.js 22 or later on PATH for Copycat")
    env = {
        **os.environ,
        "COPYCAT_CONFIG": str(config_path(m, port)),
        "PORT": str(port),
        "HOST": "127.0.0.1",
        "COPYCAT_AGENT_PRESET": agent,
    }
    if share_origin:
        env["COPYCAT_HOST_ORIGINS"] = check_origin(share_origin)
    if agent != "none":
        if not agent_bin or not Path(agent_bin).is_absolute():
            raise EditError(f"--agent {agent} needs --agent-bin with the absolute path of its CLI")
        env["COPYCAT_AGENT_BIN"] = agent_bin
    return [node, str(copycat / "src" / "server.js")], env


def launch(argv: list[str], env: dict[str, str]) -> None:  # pragma: no cover - replaces the process
    os.execve(argv[0], argv, env)
